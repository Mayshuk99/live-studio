// strings.json + ru-*.tsv (+ extra.tsv by text) → renderer/i18n-ru.js
const fs = require('fs');
const L = require('./strings.json');
const exact = {}, tpl = [];
const add = (en, ru) => {
  en = en.trim(); ru = ru.trim();
  if (!en || !ru) return;
  if (/\{\d\}/.test(en)) { if (!tpl.find(t => t[0] === en)) tpl.push([en, ru]); }
  else exact[en] = ru;
};
let n = 0;
for (const f of fs.readdirSync(__dirname).filter(f => /^ru-\d+\.tsv$/.test(f)).sort()) {
  for (const line of fs.readFileSync(__dirname + '/' + f, 'utf8').split('\n')) {
    const m = /^(\d+)\t(.*)$/.exec(line); if (!m) continue;
    const it = L[+m[1]]; if (!it) { console.error('no string', m[1]); continue; }
    // the placeholders must match
    const ph = s => (s.match(/\{\d\}/g) || []).sort().join();
    if (it.kind === 'tpl' && ph(it.s).length && !m[2].includes('{')) console.error('missing placeholders', m[1], it.s);
    for (const p of (m[2].match(/\{\d\}/g) || [])) if (!it.s.includes(p)) console.error('bad placeholder', m[1], p);
    add(it.s, m[2]); n++;
  }
}
for (const line of fs.readFileSync(__dirname + '/extra.tsv', 'utf8').split('\n')) { const [en, ru] = line.split('\t'); if (en && ru) { add(en, ru); n++; } }
const out = `/* Live Studio — Russian interface texts. Generated by the i18n tools from the English texts in the code.
   exact: English text → Russian; tpl: texts with changing parts ({0}, {1}…). */
window.I18N_RU = {
  exact: {
${Object.entries(exact).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')}
  },
  tpl: [
${tpl.map(([k, v]) => `    [${JSON.stringify(k)}, ${JSON.stringify(v)}]`).join(',\n')}
  ]
};
`;
fs.writeFileSync(process.argv[2], out);
console.log(n, 'translations ·', Object.keys(exact).length, 'exact ·', tpl.length, 'with changing parts');
